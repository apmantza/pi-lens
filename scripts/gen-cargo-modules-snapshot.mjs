#!/usr/bin/env node
/**
 * Cargo module-graph golden snapshot (#2473).
 *
 * Records what `clients/review-graph/workspace-modules.ts`'s
 * `buildModuleGraph` — the only externally observable surface for its
 * private `scanCargoModules`/`detectWorkspaceType` — reports for every
 * Cargo.toml-bearing directory under `tests/fixtures/`, plus a synthetic
 * workspace (`tests/fixtures/cargo-workspace-modules/synthetic-workspace/`)
 * built specifically to exercise: real fixture content unchanged
 * (`autofix-smoke`/`toolsmoke`, copied verbatim from the existing
 * `tests/fixtures/{autofix-smoke,tool-smoke}/rust/Cargo.toml`), a
 * `[dependencies]` table plus an internal-dependency edge
 * (`normal-with-deps` depends on workspace member `autofix-smoke`), and two
 * crates whose `name` sits under a table that is NOT `[package]` and
 * precedes it in file order (`bin-before-package`: `[[bin]] name = "..."`;
 * `metadata-before-package`: `[package.metadata.docs.rs] name = "..."`) —
 * the exact shape the pre-#2473 unscoped `extractTomlString` misread.
 *
 * The fixture is the reviewer's proof that folding
 * `extractTomlArray`/`extractTomlSection`/`extractTomlString` onto
 * `clients/cargo-manifest.ts`'s `readCargoWorkspaceMembers`/
 * `readCargoDependencyNames`/`readCargoPackageName` changed EXACTLY the two
 * misread-name rows and nothing else.
 *
 *   npm run build && node scripts/gen-cargo-modules-snapshot.mjs          # write
 *   npm run build && node scripts/gen-cargo-modules-snapshot.mjs --check  # verify
 *
 * The walk is every `Cargo.toml`-bearing directory under `tests/fixtures/`,
 * because the golden is a record of what this reader answers for fixture
 * input, not a census of the repo's own workspaces. Adding such a fixture
 * therefore adds a row (`null` when the directory is not a module-graph
 * workspace) and the snapshot is regenerated in the same change — a new clean
 * workspace under `tests/fixtures/runner-output-clean/` drifted it and reddened
 * CI (#4522 NEW-1). Excluding a fixture family instead would stop watching it.
 *
 * `tests/clients/review-graph-workspace-modules-cargo.test.ts` runs the same
 * comparison, so an accidental behavior change fails CI with a readable diff.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import {
	buildModuleGraph,
	clearModuleGraphCache,
} from "../clients/review-graph/workspace-modules.js";
import { isMainModule } from "./lib/is-main-module.mjs";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.join(HERE, "..");
export const SNAPSHOT_PATH = path.join(
	REPO_ROOT,
	"tests",
	"fixtures",
	"cargo-modules-snapshot.json",
);
const FIXTURES_ROOT = path.join(REPO_ROOT, "tests", "fixtures");

/** Recursively find every directory directly containing a `Cargo.toml`. */
export function findCargoManifestDirs(root) {
	const dirs = [];
	const walk = (dir) => {
		let entries;
		try {
			entries = fs.readdirSync(dir, { withFileTypes: true });
		} catch {
			return;
		}
		if (entries.some((e) => e.isFile() && e.name === "Cargo.toml")) {
			dirs.push(dir);
		}
		for (const entry of entries) {
			if (entry.isDirectory()) walk(path.join(dir, entry.name));
		}
	};
	walk(root);
	// Bare code-unit `.sort()` (like gen-language-snapshot.mjs), NOT
	// `localeCompare` — the golden this feeds is byte-compared (review round
	// 2, F5): a locale-aware comparator can order two entries differently than
	// the plain code-unit sort JSON.stringify/diffing assumes, silently
	// drifting the committed snapshot's row order from a fresh regen on a
	// different locale.
	return dirs.sort();
}

function relKey(dir) {
	return path.relative(REPO_ROOT, dir).replace(/\\/g, "/");
}

/** Module-graph output for one directory, with non-deterministic absolute
 * paths (`WorkspaceModule.root`, `ModuleGraph.root`) stripped — everything
 * else `buildModuleGraph` reports is deterministic given fixture content. */
function describeDir(dir) {
	clearModuleGraphCache();
	const graph = buildModuleGraph(dir);
	if (!graph) return null;
	const modules = [...graph.modules.values()]
		.map((m) => ({
			name: m.name,
			relativePath: m.relativePath,
			entrypoints: m.entrypoints,
			internalDeps: [...m.internalDeps].sort(),
			externalDeps: [...m.externalDeps].sort(),
		}))
		.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
	const dependents = Object.fromEntries(
		[...graph.dependents.entries()]
			.map(([name, deps]) => [name, [...deps].sort()])
			.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)),
	);
	return { modules, dependents };
}

export function buildSnapshot() {
	const dirs = findCargoManifestDirs(FIXTURES_ROOT);
	const byDir = {};
	for (const dir of dirs) {
		byDir[relKey(dir)] = describeDir(dir);
	}
	return {
		note: "Generated by scripts/gen-cargo-modules-snapshot.mjs - do not hand-edit.",
		byDir,
	};
}

function main() {
	const snapshot = `${JSON.stringify(buildSnapshot(), null, "\t")}\n`;
	if (process.argv.includes("--check")) {
		const current = fs.readFileSync(SNAPSHOT_PATH, "utf8");
		if (current !== snapshot) {
			process.stderr.write(
				`Cargo module-graph snapshot drifted from ${SNAPSHOT_PATH}.\n` +
					"Re-run: node scripts/gen-cargo-modules-snapshot.mjs\n",
			);
			process.exit(1);
		}
		process.stdout.write("Cargo module-graph snapshot up to date.\n");
		return;
	}
	fs.mkdirSync(path.dirname(SNAPSHOT_PATH), { recursive: true });
	fs.writeFileSync(SNAPSHOT_PATH, snapshot);
	process.stdout.write(`Wrote ${SNAPSHOT_PATH}\n`);
}

if (isMainModule(import.meta.url)) {
	main();
}
